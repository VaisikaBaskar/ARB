# backend/ai_cook/recommendation_bridge.py
# Isolated Bridge to inject AI recipes into the recommendation engine
# Additive Logic Only

import json
import os
import random

BASE_RECIPES_PATH = os.path.join(os.path.dirname(__file__), 'base_recipes.json')

from . import AI_COOK_READ_ONLY

def get_ai_recommendations(user_id, pantry_items, user_profile):
    """
    Fetches AI-generated recipe suggestions based on pantry and profile.
    Returns a list of virtual recipe objects.
    """
    # SAFETY LOCK: If module is not in read-only mode (unexpected), warn or continue.
    # In this specific context (fetching), it's safe, but we acknowledge the flag.
    if not AI_COOK_READ_ONLY:
        pass 

    # 1. Load Base Recipes
    if not os.path.exists(BASE_RECIPES_PATH):
        return []

    try:
        with open(BASE_RECIPES_PATH, 'r') as f:
            base_recipes = json.load(f)
    except Exception:
        return []

    # 2. Extract Pantry & Profile Data
    pantry_ingredients = {item["ingredient"].lower() for item in pantry_items}
    
    user_diet = user_profile.get("diet")
    user_disliked = {i.lower() for i in user_profile.get("disliked_ingredients", [])}
    # user_liked can be used for scoring boost if desired
    
    # 3. Score & Filter
    ai_recs = []
    
    for template in base_recipes:
        dish_name = template.get("dish")
        ingredients = template.get("ingredients", [])
        
        # --- FILTER: DIET ---
        # Base recipes might need diet tags in future. 
        # For now, we assume base recipes are generic or check ingredients manually?
        # Since base_recipes.json didn't have explicit diet tags in my creation step,
        # I will skip detailed diet checking to avoid false positives, 
        # OR essentially rely on the fact that I only have "Chicken", "Veg", "Egg".
        # Let's add simple heuristic if diet is "Vegetarian" or "Vegan".
        
        is_veg = True
        has_egg = False
        has_meat = False
        
        for ing in ingredients:
            name_lower = ing.get("name", "").lower()
            if name_lower in ["chicken", "fish", "beef", "meat"]:
                has_meat = True
                is_veg = False
            if name_lower in ["egg", "eggs"]:
                has_egg = True
                is_veg = False # Usually egg is not veg in some contexts, or "contains egg".
                
        if user_diet:
            diet_lower = user_diet.lower()
            if diet_lower == "vegetarian" and (has_meat or has_egg): # Broad assumption for safety
                 continue
            if diet_lower == "vegan" and (has_meat or has_egg): # Simplified
                 continue
        
        # --- FILTER: DISLIKES ---
        # Check if any ingredient is in user's dislike list
        if any(ing.get("name", "").lower() in user_disliked for ing in ingredients):
            continue

        # Calculate Match
        total_ings = len(ingredients)
        matched_count = 0
        missing_ings = []
        
        for ing in ingredients:
            name = ing.get("name", "").lower()
            if name in pantry_ingredients:
                matched_count += 1
            else:
                missing_ings.append(name)
        
        match_percent = (matched_count / total_ings) * 100 if total_ings > 0 else 0
        
        # Minimal Relevance Filter (at least 30% match)
        if match_percent < 30:
            continue
            
        # Create Virtual Recipe Object
        virtual_id = f"ai_gen_{dish_name.replace(' ', '_')}"
        
        rec_obj = {
            "recipe_id": virtual_id,
            "name": f"✨ AI Special: {dish_name.title()}", # Distinct Visual Indicator
            "cuisine": "AI Kitchen",
            "match_score": match_percent, 
            "is_full_match": (matched_count == total_ings),
            "missing_count": len(missing_ings),
            "recently_cooked": False,
            "source": "ai",         # Critical Flag
            "virtual": True,        # Critical Flag
            "description": "Auto-generated by AI Cooking Assistant based on your pantry."
        }
        
        ai_recs.append(rec_obj)

    return ai_recs
